# v8 phase 5 fixes: detailed food art for eating (the bag foods, and the FEED icon's MEAL and SNACK).
import os as _os; _ROOT = _os.environ.get('SFM_ROOT') or _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
# Each food is rendered at 28px with up to 24 colours of its own; while it is being eaten its colours are loaded into
# palette 40-63 (unused by the game), so the art keeps all its shading instead of being forced onto the room colours.
import sys
sys.path.insert(0, _ROOT + '/gen')
import icons
from decorgen import bgr
import numpy as np
def reduce_colors(hist, n):
    if len(hist) <= n: return list(hist)
    ks = list(hist); X = np.array(ks, float); Wt = np.array([hist[k] for k in ks], float)
    C = [X[Wt.argmax()]]
    for _ in range(n-1):
        d = np.min(((X[:, None, :]-np.array(C)[None])**2).sum(-1), 1)*np.sqrt(Wt); C.append(X[d.argmax()])
    C = np.array(C)
    for it in range(30):
        a = ((X[:, None, :]-C[None])**2).sum(-1).argmin(1)
        for j in range(n):
            m = a == j
            if m.any(): C[j] = (X[m]*Wt[m, None]).sum(0)/Wt[m].sum()
    return [tuple(int(round(v)) for v in c) for c in C]
NAMES = icons.ITEM_ORDER[:11]+['MEAL', 'SNACK']
NC = 24
pix = bytearray(); rows = bytearray(); meta = []; pals = []
for n in NAMES:
    im = icons.crop(icons.render_food(n, {'MEAL': 36, 'SNACK': 29}.get(n, 28))); h = len(im); w = len(im[0])
    hist = {}
    for r in im:
        for v in r:
            if v is not None: hist[tuple(v)] = hist.get(tuple(v), 0)+1
    pal = reduce_colors(hist, NC)
    def near(c): return 1+min(range(len(pal)), key=lambda i: sum((pal[i][k]-c[k])**2 for k in range(3)))
    m = (w, h, len(pix), len(rows)//2)
    for r in im:
        xs = [x for x, v in enumerate(r) if v is not None]
        rows += bytes((xs[0], xs[-1])) if xs else bytes((255, 0))
        pix += bytes(near(tuple(v)) if v is not None else 0 for v in r)
    meta.append(m); pals.append([bgr(c) for c in pal]+[0]*(NC-len(pal)))
o = ['// generated by gen/foodart.py: eating art, 28px, 24 colours each (loaded into palette 40-63 while eating)\n',
     '#define FOOD_N %d\n#define FOOD_MEAL 11\n#define FOOD_SNACK 12\n#define FOOD_PAL0 40\n' % len(NAMES),
     'static const Icon FOOD_ART[FOOD_N]={%s};\n' % ','.join('{%d,%d,%d,%d}' % (w, h, r, p) for w, h, p, r in meta),
     'static const u16 FOOD_PAL[FOOD_N][%d]={%s};\n' % (NC, ','.join('{'+','.join(map(str, p))+'}' for p in pals)),
     'static const u8 FOOD_PIX[%d]={%s};\n' % (len(pix), ','.join(map(str, pix))),
     'static const u8 FOOD_ROWS[%d]={%s};\n' % (len(rows), ','.join(map(str, rows)))]
open(_ROOT + '/foodart.h', 'w').write(''.join(o))
print('foods', len(NAMES), 'bytes', len(pix), [(m[0], m[1]) for m in meta])
