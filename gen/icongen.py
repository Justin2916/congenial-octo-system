# Builds icons.h: 44 shop icons on one shared 112-colour palette (loaded into 144-255 while the shop is open),
import os as _os; _ROOT = _os.environ.get('SFM_ROOT') or _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
# and 20px food art for the eating animation on the game's fixed colours (it is drawn over the room).
import sys, struct
sys.path.insert(0, _ROOT + '/gen')
import icons
from decorgen import nearest, bgr
import numpy as np
def reduce_colors(hist, n):
    if len(hist) <= n: return list(hist)
    ks = list(hist); X = np.array(ks, float); Wt = np.array([hist[k] for k in ks], float)
    # init: farthest-point seeding weighted by count, then weighted k-means
    C = [X[Wt.argmax()]]
    for _ in range(n-1):
        d = np.min(((X[:, None, :]-np.array(C)[None])**2).sum(-1), 1)*np.sqrt(Wt); C.append(X[d.argmax()])
    C = np.array(C)
    for it in range(30):
        a = ((X[:, None, :]-C[None])**2).sum(-1).argmin(1)
        for j in range(n):
            m = a == j
            if m.any(): C[j] = (X[m]*Wt[m, None]).sum(0)/Wt[m].sum()
    return [tuple(int(round(v)) for v in c) for c in C]
FIRST, N = 144, 112
PD = struct.unpack('<256H', open(_ROOT + '/gen/bg/pal_day.bin', 'rb').read())
rgb = lambda v: ((v & 31) << 3, ((v >> 5) & 31) << 3, ((v >> 10) & 31) << 3)
SAFE = [i for i in range(1, 73) if i not in (3, 4, 5, 6, 8, 29, 30, 33, 34, 35, 9, 0)]
SAFEC = [rgb(PD[i]) for i in SAFE]
imgs = [icons.icon(n) for n in icons.ITEM_ORDER]
hist = {}
for im in imgs:
    for r in im:
        for v in r:
            if v is not None: hist[v] = hist.get(v, 0)+1
pal = reduce_colors(hist, N); lut = {c: FIRST+nearest(pal, c) for c in hist}
pix = bytearray(); rows = bytearray(); meta = []
def emit(im, lut):
    global pix, rows
    h = len(im); w = len(im[0]); m = (w, h, len(pix), len(rows)//2)
    for r in im:
        xs = [x for x, v in enumerate(r) if v is not None]
        rows += bytes((xs[0], xs[-1])) if xs else bytes((255, 0))
        pix += bytes(lut[v] if v is not None else 0 for v in r)
    return m
for im in imgs: meta.append(emit(im, lut))
FOODS = icons.ITEM_ORDER[:11]; emeta = []
for n in FOODS:
    im = icons.crop(icons.render_food(n, 20)); el = {}
    for r in im:
        for v in r:
            if v is not None and v not in el: el[v] = SAFE[nearest(SAFEC, v)]
    emeta.append(emit(im, el))
o = ['// generated by gen/icongen.py\n#define ICON_FIRST %d\n#define ICON_N %d\n' % (FIRST, len(pal))]
o.append('typedef struct { u8 w, h; u16 row; u32 pix; } Icon;\n')
o.append('static const Icon ICONS[%d]={%s};\n' % (len(meta), ','.join('{%d,%d,%d,%d}' % (w, h, r, p) for w, h, p, r in meta)))
o.append('static const Icon EAT_ART[%d]={%s};\n' % (len(emeta), ','.join('{%d,%d,%d,%d}' % (w, h, r, p) for w, h, p, r in emeta)))
o.append('static const u16 ICON_PAL[ICON_N]={%s};\n' % ','.join(str(bgr(c)) for c in pal))
o.append('static const u8 ICON_PIX[%d]={%s};\n' % (len(pix), ','.join(map(str, pix))))
o.append('static const u8 ICON_ROWS[%d]={%s};\n' % (len(rows), ','.join(map(str, rows))))
open(_ROOT + '/icons.h', 'w').write(''.join(o))
print('icons', len(hist), '->', len(pal), 'bytes', len(pix))
