# v8.2: hardware-sprite art for the firefly release and the farewell star -> ../sprfx.h
# Run from the repo root or gen/: python3 gen/sprfx.py
# 4bpp tiles, 1D mapping, loaded at OBJ VRAM 0x06014000 (tile 512 in the bitmap modes).
# The pixels are brightness levels, not colours: ext.c builds each sprite's 16-colour palette at run time
# (the firefly's kind, the star's story colour, and the fade), and the sprites are blended additively.
import math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def radial(n, levels, power):
    c = (n - 1) / 2; R = n / 2
    img = [[0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            d = math.hypot(x - c, y - c) / R
            k = max(0.0, 1.0 - d) ** power
            img[y][x] = min(levels, math.ceil(k * levels)) if k > 0.02 else 0
    return img

def fly_core(big):
    img = [[0] * 8 for _ in range(8)]
    if big:
        for x, y in ((3, 3), (4, 3), (3, 4), (4, 4)): img[y][x] = 6
        for x, y in ((3, 2), (4, 2), (3, 5), (4, 5), (2, 3), (2, 4), (5, 3), (5, 4)): img[y][x] = 5
    else:
        img[3][3] = img[4][4] = 6; img[3][4] = img[4][3] = 5
    return img

def star_rays(n=32, main=15, diag=6):
    """four long rays and four short ones; 12 = white heart .. 9 = the faint tips"""
    img = [[0] * n for _ in range(n)]
    c = n // 2   # the centre pixel (16,16): even-sized, so the rays are one pixel off true centre on one side
    def put(x, y, v):
        if 0 <= x < n and 0 <= y < n and v > img[y][x]: img[y][x] = v
    for i in range(0, main + 1):
        v = 12 if i < 3 else 11 if i < 7 else 10 if i < 11 else 9
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            put(c + dx * i, c + dy * i, v)
            if i < 5:   # a little width near the heart
                put(c + dx * i + dy, c + dy * i + dx, 10 if i < 3 else 9)
                put(c + dx * i - dy, c + dy * i - dx, 10 if i < 3 else 9)
    for i in range(1, diag + 1):
        v = 11 if i < 2 else 10 if i < 4 else 9
        for dx, dy in ((1, 1), (-1, 1), (1, -1), (-1, -1)): put(c + dx * i, c + dy * i, v)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1): put(c + dx, c + dy, 12)
    return img

def tiles(img):
    """an image (w, h multiples of 8) -> 4bpp tiles in 1D order, as u32 words"""
    h = len(img); w = len(img[0]); out = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            for y in range(8):
                row = img[ty * 8 + y][tx * 8: tx * 8 + 8]
                v = 0
                for x, p in enumerate(row): v |= (p & 15) << (4 * x)
                out.append(v)
    return out

parts = [  # name, image
    ('FGLOW', radial(16, 4, 1.6)),       # firefly glow 16x16, levels 1-4
    ('FCORE', fly_core(True)),           # firefly heart 8x8 (near)
    ('FCORE2', fly_core(False)),         # firefly heart 8x8 (far)
    ('SGLOW', radial(32, 6, 1.8)),       # star glow 32x32, levels 1-6
    ('SRAYS', star_rays()),              # star rays 32x32, levels 9-12
]
# v8.3: one-pixel firefly dots (the jar's catch, the dance at the window): DOT+k has its pixel at (4,4) in colour k+1,
# so one palette bank holds all twelve kinds' colours
def dot(v):
    img = [[0] * 8 for _ in range(8)]; img[4][4] = v; return img
parts += [('DOT' if k == 0 else 'DOT%d' % k, dot(k + 1)) for k in range(12)]
words = []; L = ['// generated by gen/sprfx.py - hardware-sprite art (4bpp, 1D, tile 512 = 0x06014000)']
for name, img in parts:
    L.append(f'#define SPT_{name} {512 + len(words) // 8}')
    words += tiles(img)
L.append(f'#define SPR_TILE_WORDS {len(words)}')
L.append('static const u32 SPR_TILES[SPR_TILE_WORDS] = {')
for i in range(0, len(words), 8): L.append('  ' + ','.join(f'0x{w:08X}' for w in words[i:i + 8]) + ',')
L.append('};')
open(os.path.join(ROOT, 'sprfx.h'), 'w').write('\n'.join(L) + '\n')
print('sprfx.h:', len(words) // 8, 'tiles')
