# Phase 4: minigame objects and the farewell star, drawn at every size the game uses.
import os as _os; _ROOT = _os.environ.get('SFM_ROOT') or _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
# Codes: 0 clear, 1 main, 2 highlight, 3 shade, 4 leaf, 5 outline, 6 glint, 7 deep shade
import math, sys
sys.path.insert(0, _ROOT + '/gen')
from baricons import disc, box, poly, U, M, seg

def shade_grid(f, w, h, cx, cy, r, outline=True, extra=None):
    S = 3
    cov = [[sum(f(x+(i+0.5)/S, y+(j+0.5)/S) for i in range(S) for j in range(S))/(S*S) for x in range(w)] for y in range(h)]
    on = lambda x, y: 0 <= x < w and 0 <= y < h and cov[y][x] >= 0.5
    g = [[0]*w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            if on(x, y):
                nx = (x+0.5-cx)/r; ny = (y+0.5-cy)/r; d = -0.6*nx-0.75*ny
                g[y][x] = 2 if d > 0.45 else 1 if d > -0.25 else 3 if d > -0.75 else 7
            elif outline and any(on(x+dx, y+dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))): g[y][x] = 5
    if extra: extra(g, w, h)
    return g
def star_pts(cx, cy, r1, r2, rot=-math.pi/2):
    return [(cx+(r1 if i % 2 == 0 else r2)*math.cos(rot+i*math.pi/5), cy+(r1 if i % 2 == 0 else r2)*math.sin(rot+i*math.pi/5)) for i in range(10)]
def star(n):
    if n == 5: return [[0, 0, 1, 0, 0], [0, 1, 2, 1, 0], [1, 2, 6, 1, 1], [0, 1, 1, 3, 0], [0, 1, 0, 1, 0]]
    c = (n-1)/2; o = 1 if n >= 10 else 0
    f = poly(star_pts(c+0.5, c+0.7, n/2-o-0.2, (n/2-o)*0.48))
    def glint(g, w, h):
        x, y = int(c-n*0.12), int(c-n*0.05)
        if g[y][x] in (1, 2): g[y][x] = 6
    return shade_grid(f, n, n, c+0.5, c+0.7, n/2, outline=n >= 10, extra=glint)
def berry(n):
    r = n*0.36; cx = n/2; cy = n*0.58
    f = U(disc(cx, cy, r))
    def leaf(g, w, h):
        for (x, y) in ((n//2-1, 1), (n//2, 0), (n//2+1, 1), (n//2+2, 1), (n//2-2, 2), (n//2, 1), (n//2+1, 2)):
            if 0 <= x < w and 0 <= y < h: g[y][x] = 4
        gx, gy = int(cx-r*0.45), int(cy-r*0.4)
        g[gy][gx] = 6
    return shade_grid(f, n, n, cx, cy, r, extra=leaf)
def rock(n, k=0):
    cx = n/2; cy = n*0.56; r = n*0.42
    f = lambda x, y: ((x-cx)/(r*1.08))**2+((y-cy)/(r*0.92))**2 <= 1+0.06*math.sin(math.atan2(y-cy, x-cx)*5+k*1.3)
    def crack(g, w, h):
        pts = [(0.62, 0.34), (0.55, 0.5), (0.66, 0.62)] if k == 0 else [(0.36, 0.38), (0.45, 0.52), (0.36, 0.66)]
        for (u, v) in pts:
            x, y = int(u*n), int(v*n)
            if g[y][x] in (1, 2, 3): g[y][x] = 7
        for (u, v) in (((0.3, 0.75), (0.7, 0.3)) if k == 0 else ((0.7, 0.75), (0.3, 0.3))):
            x, y = int(u*n), int(v*n)
            if g[y][x] in (1, 3): g[y][x] = 3 if g[y][x] == 1 else 7
    return shade_grid(f, n, n, cx-n*0.05, cy-n*0.05, r, extra=crack)

def arrow(w=14, h=20):
    # a chunky rounded chevron pointing left
    f = U(seg(w-3, 3, 4, h/2, 2.6), seg(4, h/2, w-3, h-3, 2.6))
    return shade_grid(f, w, h, w/2, h/2, w/2)
def balloon():
    f = U(lambda x, y: ((x-6.5)/5.3)**2+((y-6.5)/6.3)**2 <= 1, poly([(5.2, 12.2), (7.8, 12.2), (6.5, 10.5)]))
    def shine(g, w, h):
        for (x, y) in ((4, 3), (3, 4), (4, 4)): g[y][x] = 6
    return shade_grid(f, 13, 15, 6.5, 6.5, 6, extra=shine)
def bundle():
    f = U(disc(7, 8, 5.6), poly([(4.5, 4), (3, 0.8), (6.5, 3.2)]), poly([(9.5, 4), (11, 0.8), (7.5, 3.2)]))
    def dots(g, w, h):
        for (x, y) in ((5, 6), (9, 7), (6, 10), (10, 11), (4, 9), (8, 4)):
            if g[y][x] in (1, 2, 3, 7): g[y][x] = 6
    return shade_grid(f, 14, 15, 7, 8, 6, extra=dots)
SETS = [('STAR', [star(5*s) for s in range(1, 6)]), ('BERRY', [berry(12)]), ('ROCK', [rock(12), rock(18, 0), rock(18, 1)]), ('ARROW', [arrow()]), ('BALLOON', [balloon()]), ('BUNDLE', [bundle()])]
def write():
    o = ['// generated by gen/minis.py: minigame objects and the farewell star (codes: 0 clear,1 main,2 light,3 shade,4 leaf,5 outline,6 glint,7 deep)\n']
    o.append('typedef struct { u8 w, h; u16 off; } MiniArt;\n')
    data = []; ents = []
    for name, grids in SETS:
        for g in grids:
            ents.append((len(g[0]), len(g), len(data))); data += [v for row in g for v in row]
    o.append('static const u8 MINI_PIX[%d]={%s};\n' % (len(data), ','.join(map(str, data))))
    o.append('static const MiniArt MINI_ART[%d]={%s};\n' % (len(ents), ','.join('{%d,%d,%d}' % e for e in ents)))
    o.append('enum { MA_STAR1, MA_STAR2, MA_STAR3, MA_STAR4, MA_STAR5, MA_BERRY, MA_ROCK2, MA_ROCK3A, MA_ROCK3B, MA_ARROW, MA_BALLOON, MA_BUNDLE };\n')
    open(_ROOT + '/minis.h', 'w').write(''.join(o))
