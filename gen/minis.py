    R = {0: None, 1: (236, 64, 72), 2: (250, 140, 160), 3: (190, 40, 60), 4: (80, 190, 70), 5: (32, 32, 72), 6: (255, 255, 255), 7: (140, 30, 50)}
    K = {0: None, 1: (150, 150, 170), 2: (216, 216, 248), 3: (100, 104, 130), 4: (80, 190, 70), 5: (32, 32, 72), 6: (255, 255, 255), 7: (70, 72, 100)}
