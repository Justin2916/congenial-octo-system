# Builds critters.h: the new 13 critter forms x 6 poses at 16/32/48/64 px, palette-indexed for the game.
import os as _os; _ROOT = _os.environ.get('SFM_ROOT') or _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
# Each form gets its own 37-colour palette loaded into the free "critter slot" entries when it is drawn.
# The star album shows many forms at once, so it gets a separate 32px set on one shared palette
# that is loaded into the room-background shade range (unused on the album screen).
import sys, math
sys.path.insert(0, _ROOT + '/gen')
import critters as C

SLOT_IDX = list(range(120, 144)) + list(range(73, 80)) + list(range(90, 96))   # 37 entries
SIZES = (16, 32, 48, 64)
ALB_FIRST, ALB_N = 144, 112

def d2(a, b): return sum((a[i]-b[i])**2 for i in range(3))
def reduce_colors(hist, n):
    cols = dict(hist)
    while len(cols) > n:
        ks = list(cols); best = None
        for i in range(len(ks)):
            for j in range(i+1, len(ks)):
                w = min(cols[ks[i]], cols[ks[j]]); d = d2(ks[i], ks[j]) * w
                if best is None or d < best[0]: best = (d, ks[i], ks[j])
        _, a, b = best; wa, wb = cols.pop(a), cols.pop(b)
        m = tuple(int(round((a[k]*wa + b[k]*wb)/(wa+wb))) for k in range(3))
        cols[m] = cols.get(m, 0) + wa + wb
    return list(cols)
def nearest(pal, c): return min(range(len(pal)), key=lambda i: d2(pal[i], c))
def bgr(c): return (c[0]>>3) | ((c[1]>>3)<<5) | ((c[2]>>3)<<10)

pix = bytearray(); rows = bytearray(); off = []; pals = []
ALL = C.ORDER + C.GIRL_ORDER                     # v8: girl versions follow the 23 base forms
for f, name in enumerate(ALL):
    imgs = {(p, s): C.render(name, p, s) for p in C.POSES for s in SIZES}
    imgs.update({(p, 'm'): C.render(name, p, 48, mirror=True) for p in C.POSES})   # facing right, re-lit
    hist = {}
    for im in imgs.values():
        for r in im:
            for v in r:
                if v is not None: hist[v] = hist.get(v, 0) + 1
    pal = reduce_colors(hist, len(SLOT_IDX)); pals.append(pal)
    lut = {c: SLOT_IDX[nearest(pal, c)] for c in hist}
    fo = []
    for p in C.POSES:
        po = []
        for s in SIZES:
            im = imgs[(p, s)]; po.append((len(pix), len(rows)))
            for r in im:
                xs = [x for x, v in enumerate(r) if v is not None]
                rows += bytes((xs[0], xs[-1])) if xs else bytes((255, 0))
                pix += bytes(lut[v] if v is not None else 0 for v in r)
        im = imgs[(p, 'm')]; po.append((len(pix), len(rows)))
        for r in im:
            xs = [x for x, v in enumerate(r) if v is not None]
            rows += bytes((xs[0], xs[-1])) if xs else bytes((255, 0))
            pix += bytes(lut[v] if v is not None else 0 for v in r)
        fo.append(po)
    off.append(fo)
    print(name, len(hist), 'colours ->', len(pal), file=sys.stderr)

# album set: 32px idle, shared palette
ahist = {}; aimgs = []
for name in C.ORDER:
    im = C.render(name, 'idle', 32); aimgs.append(im)
    for r in im:
        for v in r:
            if v is not None: ahist[v] = ahist.get(v, 0) + 1
apal = reduce_colors(ahist, ALB_N); alut = {c: ALB_FIRST + nearest(apal, c) for c in ahist}
apix = bytearray(); arows = bytearray()
for im in aimgs:
    for r in im:
        xs = [x for x, v in enumerate(r) if v is not None]
        arows += bytes((xs[0], xs[-1])) if xs else bytes((255, 0))
        apix += bytes(alut[v] if v is not None else 0 for v in r)
print('album', len(ahist), '->', len(apal), file=sys.stderr)

def arr(t, name, data, per=32):
    s = 'static const %s %s[%d]={' % (t, name, len(data))
    s += ','.join(str(v) for v in data) + '};\n'
    return s
o = ['// generated by gen/critgen.py\n#define CR_FORMS %d\n#define CR_BASE_FORMS %d\n#define CR_POSES %d\n#define CR_SLOTS %d\n' % (len(ALL), len(C.ORDER), len(C.POSES), len(SLOT_IDX))]
o.append(arr('u8', 'CR_GIRL', [ALL.index(n+'~G') if n+'~G' in ALL else i for i, n in enumerate(C.ORDER)]))
o.append('enum { ' + ', '.join('POSE_'+p.upper() for p in C.POSES) + ' };\n')
o.append(arr('u8', 'CR_SLOT_IDX', SLOT_IDX))
o.append('static const u16 CR_PAL[CR_FORMS][CR_SLOTS]={' + ','.join('{' + ','.join(str(bgr(c)) for c in p + [(0,0,0)]*(len(SLOT_IDX)-len(p))) + '}' for p in pals) + '};\n')
o.append('static const u32 CR_PIXOFF[CR_FORMS][CR_POSES][5]={' + ','.join('{' + ','.join('{' + ','.join(str(a) for a, b in po) + '}' for po in fo) + '}' for fo in off) + '};\n')
o.append('static const u32 CR_ROWOFF[CR_FORMS][CR_POSES][5]={' + ','.join('{' + ','.join('{' + ','.join(str(b//2) for a, b in po) + '}' for po in fo) + '}' for fo in off) + '};\n')
o.append(arr('u8', 'CR_PIX', pix)); o.append(arr('u8', 'CR_ROWS', rows))
o.append('#define ALB_FIRST %d\n#define ALB_N %d\n' % (ALB_FIRST, len(apal)))
o.append(arr('u16', 'ALB_PAL', [bgr(c) for c in apal])); o.append(arr('u8', 'ALB_PIX', apix)); o.append(arr('u8', 'ALB_ROWS', arows))
open(_ROOT + '/critters.h', 'w').write(''.join(o))
print('pix', len(pix), 'rows', len(rows), 'album', len(apix), file=sys.stderr)
