# v8.2b: the watering can for the night garden -> ../can.h
# Run from the repo root or gen/: python3 gen/can.py
# The can is described as shapes, turned to its pose, then drawn at game size (8x supersampled, majority colour per
# pixel) with a one-pixel outline, and mapped onto the garden palette (gen/garden_art.py via garden.h), which is
# loaded whenever the garden is on screen. Two poses: carried, and tipped to pour. For each pose the header also
# gives the rose's face (where the water leaves the spout), so the shower starts there and nowhere else.
import math, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SS = 8
OUT = (30, 34, 44); G0 = (232, 250, 236); G1 = (150, 214, 168); G2 = (96, 174, 124); G3 = (66, 136, 100); G4 = (44, 98, 78)
BR1 = (255, 226, 140); BR2 = (206, 158, 70); HDL = (58, 70, 80); ROSE_FACE = (255, 255, 0)   # (a marker, not drawn)

def render(angle, W=30, H=26, cx=11.0, cy=14.0):
    from PIL import Image, ImageDraw
    a = math.radians(angle); ca, sa = math.cos(a), math.sin(a)
    def T(x, y):
        x -= cx; y -= cy
        return ((x * ca - y * sa + W / 2) * SS, (x * sa + y * ca + H / 2 - 2) * SS)
    big = Image.new('RGBA', (W * SS, H * SS), (0, 0, 0, 0)); d = ImageDraw.Draw(big)
    pts = [T(5.5 + 9 * (1 - math.cos(math.pi * t / 20)) / 2, 6.5 - 4.6 * math.sin(math.pi * t / 20)) for t in range(21)]
    d.line(pts, fill=HDL + (255,), width=int(2.3 * SS))                                   # the handle
    d.line([T(15.5, 15), T(21, 9.5)], fill=G3 + (255,), width=int(2.2 * SS))               # the spout
    d.polygon([T(4.2, 6), T(15.8, 6), T(16.4, 17.2), T(3.6, 17.2)], fill=G2 + (255,))      # the body
    for x0, x1, c in ((3.6, 5.6, G1), (5.6, 6.6, G0), (13.6, 15.0, G3), (15.0, 16.4, G4)):
        d.polygon([T(x0, 6), T(x1, 6), T(x1 + (0.6 if x1 > 10 else -0.6), 17.2), T(x0 + (0.6 if x0 > 10 else -0.6), 17.2)], fill=c + (255,))
    d.polygon([T(3.6, 15.6), T(16.4, 15.6), T(16.4, 17.2), T(3.6, 17.2)], fill=G4 + (255,))   # its dark foot
    d.polygon([T(4.2, 6), T(15.8, 6), T(15.9, 7.2), T(4.1, 7.2)], fill=G3 + (255,))          # the rim
    rx, ry = T(21.6, 9.0); r = 2.2 * SS
    d.ellipse((rx - r, ry - r, rx + r, ry + r), fill=BR2 + (255,))
    d.ellipse((rx - r * 0.55 - SS * 0.4, ry - r * 0.55 - SS * 0.4, rx + r * 0.25, ry + r * 0.25), fill=BR1 + (255,))
    fx, fy = T(23.4, 9.0)                                                                # the rose's face, out along the spout
    small = Image.new('RGBA', (W, H), (0, 0, 0, 0)); p = big.load(); q = small.load()
    for y in range(H):
        for x in range(W):
            cnt = {}
            for yy in range(y * SS, y * SS + SS):
                for xx in range(x * SS, x * SS + SS):
                    c = p[xx, yy]
                    if c[3] > 0: cnt[c[:3]] = cnt.get(c[:3], 0) + 1
            if sum(cnt.values()) >= SS * SS * 0.45: q[x, y] = max(cnt, key=cnt.get) + (255,)
    o = small.copy(); oq = o.load()
    for y in range(H):
        for x in range(W):
            if q[x, y][3]: continue
            if any(0 <= x + dx < W and 0 <= y + dy < H and q[x + dx, y + dy][3] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                oq[x, y] = OUT + (255,)
    bb = o.getbbox(); o = o.crop(bb)
    return o, (int(fx / SS) - bb[0], int(fy / SS) - bb[1])

def garden_palette():
    h = open(os.path.join(ROOT, 'garden.h')).read()
    idx = [int(v) for v in re.search(r'GP_IDX\[GP_N\]=\{([^}]*)\}', h).group(1).split(',')]
    pal = [int(v) for v in re.search(r'GP_PAL\[GP_N\]=\{([^}]*)\}', h).group(1).split(',')]
    return [(i, ((c & 31) * 8, ((c >> 5) & 31) * 8, ((c >> 10) & 31) * 8)) for i, c in zip(idx, pal)]

def main():
    gp = garden_palette()
    near = lambda c: min(gp, key=lambda e: sum((e[1][k] - c[k]) ** 2 for k in range(3)))[0]
    L = ['// generated by gen/can.py - the night garden\'s watering can (garden palette indices, 0 = clear)']
    for name, ang in (('UP', 0), ('TIP', 42)):
        im, (fx, fy) = render(ang); px = im.load()
        L.append(f'#define CAN_{name}_W {im.width}\n#define CAN_{name}_H {im.height}\n#define CAN_{name}_RX {fx}\n#define CAN_{name}_RY {fy}   // the rose\'s face')
        rows = []
        for y in range(im.height):
            rows.append(','.join(str(near(px[x, y][:3]) if px[x, y][3] else 0) for x in range(im.width)))
        L.append(f'static const u8 CAN_{name}[{im.height}][{im.width}]={{\n  ' + ',\n  '.join('{' + r + '}' for r in rows) + '};')
    open(os.path.join(ROOT, 'can.h'), 'w').write('\n'.join(L) + '\n')
    print('can.h written')

if __name__ == '__main__':
    main()
