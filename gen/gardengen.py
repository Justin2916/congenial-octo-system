# v8.1 B2: turns gen/garden_art.py into ../garden.h (the moonflowers and the night visitors).
# 35 colours: palette 40-63 (the food's range, free in the yard) and 244-255 (past the decor bands).
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
import garden_art as A

FL = A.FLOWER_COLS
COLOURS = [('k', A.PAL['k']), ('d', A.PAL['d']), ('b', A.PAL['b']), ('t', A.PAL['t']), ('c', A.PAL['c']),
           ('w', A.PAL['w']), ('y', A.PAL['y']), ('o', A.PAL['o']), ('p', A.PAL['p']), ('g', A.PAL['g']),
           ('G', A.PAL['G']), ('L', A.PAL['L']), ('v', A.PAL['v']), ('V', A.PAL['V']), ('r', A.PAL['r']),
           ('R', A.PAL['R']), ('x', A.PAL['x']), ('X', A.PAL['X']), ('z', A.PAL['z']), ('S', A.PAL['S']),
           ('n', A.PAL['n']), ('N', A.PAL['N']), ('M', A.PAL['M']), ('5', A.PAL['5']), ('7', A.PAL['7'])]
for name in FL:  # five flower colours, light and mid
    COLOURS += [(name + '1', FL[name][0]), (name + '2', FL[name][1])]
assert len(COLOURS) <= 36, len(COLOURS)
SLOT = {}
for i, (ch, _) in enumerate(COLOURS): SLOT[ch] = 40 + i if i < 24 else 244 + (i - 24)
SAME = {'u': 'MINT1', 'U': 'MINT2', 'f': 'y', 's': 't', 'C': 'SILVER1', 'e': 'SILVER2', 'Y': 'y', '6': '5'}
MARK = {'1': 1, '2': 2, 'A': 2, '3': 3, 'B': 4}   # petals: coloured when drawn (twinglow: 1/2 first bloom, 3/4 second)

def rgb15(c): return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)
def code(ch):
    if ch == '.': return 0
    if ch in MARK: return MARK[ch]
    ch = SAME.get(ch, ch)
    return SLOT[ch]

SPRITES = []   # (enum name, frame)
def add(name, fr): SPRITES.append((name, fr))
add('GS_SEED', A.SEED); add('GS_SPROUT', A.SPROUT); add('GS_BUD', A.BUD); add('GS_STEM', A.STEM); add('GS_MOUND', A.MOUND)
add('GS_BLOOM0', A.BLOOM_HEAD[0]); add('GS_BLOOM1', A.BLOOM_HEAD[1])
add('GS_STAR0', A.STARBLOOM[0]); add('GS_STAR1', A.STARBLOOM[1]); add('GS_MOON0', A.MOONLILY[0]); add('GS_MOON1', A.MOONLILY[1])
add('GS_TWIN', A.TWIN)
VIS = []   # name, first sprite, frame count, sequence
for name, frames, seq, rare in A.VISITORS:
    first = len(SPRITES)
    for i, f in enumerate(frames): add('GS_' + name.replace(' ', '_') + str(i), f)
    VIS.append((name, first, len(frames), seq, rare))

pix = []; table = []
for name, fr in SPRITES:
    h = len(fr); w = len(fr[0]); off = len(pix)
    for r in fr:
        assert len(r) == w, (name, r)
        pix += [code(ch) for ch in r]
    table.append((name, w, h, off))

out = ['// generated by gen/gardengen.py from gen/garden_art.py - do not edit',
       f'#define GP_N {len(COLOURS)}',
       'static const u8 GP_IDX[GP_N]={' + ','.join(str(SLOT[c]) for c, _ in COLOURS) + '};',
       'static const u16 GP_PAL[GP_N]={' + ','.join(str(rgb15(v)) for _, v in COLOURS) + '};',
       '// the five flower colours: palette index of light, mid (SILVER, ROSE, GOLD, SKY, MINT)',
       'static const u8 GP_PETAL[5][2]={' + ','.join('{%d,%d}' % (SLOT[n + '1'], SLOT[n + '2']) for n in FL) + '};',
       '// the aurora\'s bands: green, mint, teal, violet, pink, violet, teal, mint',
       'static const u8 GP_AURORA[8]={' + ','.join(str(SLOT[SAME.get(c, c)]) for c in 'LuUVpVUu') + '};',
       '#define GP_GLOW_LUNA0 %d' % SLOT['MINT1'], '#define GP_GLOW_LUNA1 %d' % SLOT['MINT2'], '#define GP_GOLD2 %d' % SLOT['GOLD2'],
       '#define GP_K %d' % SLOT['k'], '#define GP_Y %d' % SLOT['y'], '#define GP_W %d' % SLOT['w'], '#define GP_SKY1 %d' % SLOT['SKY1'], '#define GP_SKY2 %d' % SLOT['SKY2'],
       'enum {' + ','.join(n for n, *_ in table) + ', GS_N};',
       'typedef struct { u8 w, h; u16 off; } GSpr;',
       'static const GSpr GSPR[GS_N]={' + ','.join('{%d,%d,%d}' % (w, h, o) for _, w, h, o in table) + '};',
       f'static const u8 GPIX[{len(pix)}]={{' + ','.join(map(str, pix)) + '};',
       f'#define GV_N {len(VIS)}',
       'typedef struct { const char *name; u8 first, frames, seq_n, rare; const u8 *seq; } GVis;']
for name, first, n, seq, rare in VIS:
    out.append('static const u8 GSEQ_%s[%d]={%s};' % (name.replace(' ', '_'), len(seq), ','.join(map(str, seq))))
out.append('static const GVis GVIS[GV_N]={' + ','.join('{"%s",%d,%d,%d,%d,GSEQ_%s}' % (name, first, n, len(seq), rare, name.replace(' ', '_')) for name, first, n, seq, rare in VIS) + '};')
out.append('static const s8 GHOP_FROG[%d]={%s};' % (len(A.FROG_HOP), ','.join(map(str, A.FROG_HOP))))
out.append('static const s8 GHOP_CRICKET[%d]={%s};' % (len(A.CRICKET_HOP), ','.join(map(str, A.CRICKET_HOP))))
dst = os.path.join(os.path.dirname(__file__), '..', 'garden.h')
open(dst, 'w').write('\n'.join(out) + '\n')
print(dst, len(pix), 'bytes of pixels,', len(SPRITES), 'frames,', len(COLOURS), 'colours')
