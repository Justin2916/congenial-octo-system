# v8.2c: the yard's poops, in three sizes for three depths (front, middle, back) -> ../poop.h
# Run from the repo root or gen/: python3 gen/poop.py
# The same colours as the original's room poops (palette 1 outline, 24 body, 35 mid, 25 light, 3 shine), drawn at
# full detail instead of doubled pixels: a swirl of three tiers lit from the top-left, with a one-pixel outline.
import math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SS = 8
OUTLINE, BODY, MID, LIGHT, SHINE = 1, 24, 35, 25, 3

def render(W, H):
    """a W x H poop (outline included): three tiers, each an ellipse, shaded by its normal"""
    inner_w, inner_h = W - 2, H - 2
    tiers = [  # (centre x, centre y, rx, ry) in 0..1 of the inner box
        (0.50, 0.80, 0.50, 0.24),
        (0.48, 0.52, 0.36, 0.20),
        (0.50, 0.28, 0.22, 0.16),
    ]
    img = [[0] * W for _ in range(H)]
    for y in range(inner_h):
        for x in range(inner_w):
            hits = {}
            for sy in range(SS):
                for sx in range(SS):
                    u = (x + (sx + 0.5) / SS) / inner_w; v = (y + (sy + 0.5) / SS) / inner_h
                    best = None
                    for k, (cx, cy, rx, ry) in enumerate(tiers):
                        dx = (u - cx) / rx; dy = (v - cy) / ry
                        if dx * dx + dy * dy <= 1:
                            # light from the top-left: the side facing it is bright, the bottom-right dark
                            nz = math.sqrt(max(0.0, 1 - dx * dx - dy * dy)); lit = (-dx * 0.55 - dy * 0.75 + nz * 0.6)
                            best = (k, lit)
                    # the tip: a little curl on top
                    if best is None and (u - 0.56) ** 2 / 0.010 + (v - 0.10) ** 2 / 0.006 <= 1: best = (3, 0.6)
                    if best is not None:
                        k, lit = best
                        c = SHINE if lit > 0.95 else LIGHT if lit > 0.55 else MID if lit > 0.15 else BODY
                        hits[c] = hits.get(c, 0) + 1
            if sum(hits.values()) >= SS * SS * 0.45: img[y + 1][x + 1] = max(hits, key=hits.get)
    # the creases between tiers: a darker line where one tier sits on the next
    for k in range(1, 3):
        cx, cy, rx, ry = tiers[k]
        yy = int(round((cy + ry * 0.92) * inner_h)) + 1
        for x in range(W):
            u = (x - 1 + 0.5) / inner_w
            if abs(u - cx) < rx * 0.85 and 0 < yy < H - 1 and img[yy][x]: img[yy][x] = BODY
    # outline
    out = [row[:] for row in img]
    for y in range(H):
        for x in range(W):
            if img[y][x]: continue
            if any(0 <= x + dx < W and 0 <= y + dy < H and img[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                out[y][x] = OUTLINE
    return out

SIZES = (('FRONT', 16, 11), ('MID', 13, 9), ('BACK', 10, 7))

def main():
    L = ['// generated by gen/poop.py - the yard\'s poops: front, middle and back sizes (palette indices, 0 = clear)']
    for name, w, h in SIZES:
        img = render(w, h)
        L.append(f'#define POOP_{name}_W {w}\n#define POOP_{name}_H {h}')
        L.append(f'static const u8 POOP_{name}[{h}][{w}]={{\n  ' + ',\n  '.join('{' + ','.join(str(v) for v in r) + '}' for r in img) + '};')
    open(os.path.join(ROOT, 'poop.h'), 'w').write('\n'.join(L) + '\n')
    print('poop.h written')

if __name__ == '__main__':
    main()
