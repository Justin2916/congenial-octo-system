# wall picture for the room: source photo -> 30x24, 24 colours, GBA 15-bit; writes picture.h
from PIL import Image, ImageEnhance
import sys
src=Image.open(sys.argv[1] if len(sys.argv)>1 else 'gen/picture_src.jpg').convert('RGB')
W,H=src.size; px=src.load()
def dark(c): return sum(c)<60
l=0
while l<W//4 and all(dark(px[l,y]) for y in range(H//4,3*H//4,5)): l+=1
r=W-1
while r>3*W//4 and all(dark(px[r,y]) for y in range(H//4,3*H//4,5)): r-=1
t=0
while t<H//4 and all(dark(px[x,t]) for x in range(W//4,3*W//4,5)): t+=1
b=H-1
while b>3*H//4 and all(dark(px[x,b]) for x in range(W//4,3*W//4,5)): b-=1
src=src.crop((l+1,t+1,r,b))
s=src.resize((30,24),Image.LANCZOS); s=ImageEnhance.Color(s).enhance(1.3); s=ImageEnhance.Contrast(s).enhance(1.1)
q=s.quantize(colors=24,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE)
pal=q.getpalette()[:24*3]; idx=list(q.getdata())
def rgb555(r,g,b): return (r>>3)|((g>>3)<<5)|((b>>3)<<10)
day=[rgb555(*pal[i*3:i*3+3]) for i in range(24)]
night=[]
for i in range(24):
    r,g,b=pal[i*3:i*3+3]; night.append(rgb555(int(r*0.45),int(g*0.45),min(255,int(b*0.55)+18)))
with open('picture.h','w') as f:
    f.write('// generated by gen/picture.py\n#define PIC_W 30\n#define PIC_H 24\n')
    f.write('static const u16 PIC_PAL_DAY[24]={%s};\n'%','.join('0x%04x'%v for v in day))
    f.write('static const u16 PIC_PAL_NIGHT[24]={%s};\n'%','.join('0x%04x'%v for v in night))
    f.write('static const u8 PIC_PIX[720]={%s};\n'%','.join(str(v) for v in idx))
print('ok', max(idx))
